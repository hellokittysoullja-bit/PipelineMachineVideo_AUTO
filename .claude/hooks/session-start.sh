#!/bin/bash
# Стартовый хук облачной сессии: поставить то, без чего не поедут ни
# тесты, ни локальный режиссёр кадра (scripts/shot_brief_director.py).
#
# ЗАЧЕМ МОДЕЛЬ ЗДЕСЬ. Решение владельца 16.09 по замеру: локальный мозг
# даёт 73 попадания из 116 против 58 у прежнего способа (запрос секции) и
# 49 у выключенного пофразового автомата. То есть он лучше всего, что было
# до него. Честный предел записан рядом и не прячется: сама сессия на том
# же задании даёт 85, поэтому локальный путь — для случая «без сессии»
# (ночной прогон, офлайн), а не «вместо сессии».
#
# ЦЕНА — ЗАМЕРЕНА, НЕ ОЦЕНЕНА. На PyPI у llama-cpp-python лежит ТОЛЬКО
# sdist (проверено запросом к API: один файл, 71.4 МБ исходников, ни
# одного готового колеса), поэтому здесь движок КОМПИЛИРУЕТСЯ. Замер в
# чистом venv этого контейнера: 134 секунды, rc=0, импорт работает.
# Загрузка модели — 2.3 ГБ; замерены 100 МБ диапазонным запросом (25 МБ/с),
# отсюда ~1.6 мин, и это ЭКСТРАПОЛЯЦИЯ СКОРОСТИ, а не замер полной
# загрузки. Итого первый запуск примерно 4 минуты. Платится один раз:
# состояние контейнера кэшируется после того, как хук отработал, и
# следующая сессия проходит его за 2 секунды (тоже замер).
#
# Опасение «10+ минут компиляции», с которого этот хук обсуждался, замером
# НЕ подтвердилось — поэтому режим синхронный, а не асинхронный.
#
# FAIL-OPEN, и это не вежливость. Ни один шаг не имеет права не дать
# сессии стартовать: нет модели — shot_brief_director.py просто назовёт
# команду установки и ничего не сделает, то есть поведение ровно такое же,
# как до появления этого хука.
set -uo pipefail

# Только в облаке. На машине владельца окружение своё, и трогать его
# стартовым хуком нельзя.
if [ "${CLAUDE_CODE_REMOTE:-}" != "true" ]; then
  exit 0
fi

cd "${CLAUDE_PROJECT_DIR:-$(dirname "$0")/../..}" || exit 0

PY="$(command -v python3 || command -v python)"
[ -n "$PY" ] || { echo "[hook] python не найден"; exit 0; }

echo "[hook] 1/3 зависимости проекта"
"$PY" -m pip install --quiet -r requirements.txt \
  || echo "[hook] requirements.txt не доставлен — часть тестов не пойдёт"

echo "[hook] 2/3 движок локального режиссёра"
if "$PY" -c 'import llama_cpp' 2>/dev/null; then
  echo "[hook] движок уже стоит"
else
  # Без индекса и без закрепления версии: готовые сборки из официального
  # индекса автора пакета собраны под musl и на обычном дистрибутиве
  # падают импортом (проверено живой установкой). Здесь собирается из
  # исходников, и это штатный путь.
  "$PY" -m pip install --quiet llama-cpp-python \
    || echo "[hook] движок не собрался — локальный режиссёр будет недоступен"
fi

echo "[hook] 3/3 модель (пропускается, если уже на месте)"
"$PY" scripts/setup_local_director.py --yes \
  || echo "[hook] модель не поставлена — режиссёр назовёт команду установки сам"

exit 0
