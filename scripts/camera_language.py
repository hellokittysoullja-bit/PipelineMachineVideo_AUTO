# -*- coding: utf-8 -*-
"""ЯЗЫК КАМЕРЫ: драматургия выбирает, КАК движется кадр.

ЗАЧЕМ. Замер на эпизоде 02 (142 кадра, 15.09): характер движения кадра
решает ХЭШ ИМЕНИ ФАЙЛА у **118 кадров из 142 (83%)**, смысл — у 24 (17%,
это цифра на экране и начало раздела). Направление (наезд или отъезд)
решает хэш у **всех 142 без единого исключения** — `kb_hash_choices()`:

    h = md5(имя_файла); zoom_in = bool(h & 1)

При этом драматургическая стадия каждой фразы УЖЕ посчитана и лежит в
`media_plan/speech_plan.json` — **142 из 142 размечены**. То есть в системе
одновременно есть орган, который понимает драматургию, и камера, которая о
ней не знает ничего. Это не отсутствие данных, это отсутствие провода
между двумя уже построенными слоями.

Тот же класс уже был найден и измерен в цвете: `GRADE_HASH_JITTER`
(вариация грейда по хэшу имени файла) оказалась «единственным из четырёх
модуляторов без связи с содержимым» и выключена по замеру. Здесь то же
самое, только в камере — и в камере это заметнее: движение зритель видит
всегда, а ±4% контраста почти никогда.

ЧТО ИМЕННО ДЕЛАЕТСЯ — И ЧЕГО СОЗНАТЕЛЬНО НЕ ДЕЛАЕТСЯ.

Модуль НЕ назначает кадру один режим движения. Он **сужает палитру** до
тех режимов, которые уместны на этой стадии рассказа, а выбор ВНУТРИ
палитры оставляет прежнему хэшу и прежнему anti-repeat. Причина не в
осторожности, а в замере: на эпизоде 02 стадия «доказательство» покрывает
34 кадра. Жёсткое правило «доказательство -> static_hold» дало бы 34
одинаковых кадра и заменило бы один почерк автослайдшоу другим — ровно то,
на что жалуется докстринг `choose_motion_mode()` («все кадры дышат одним и
тем же классом движения»). Стадия отвечает на вопрос «что здесь уместно»,
хэш — на вопрос «какой из уместных взять сейчас».

Этот приём в коде НЕ новый: у ХУКА он уже работает ровно так —
`snap_push if (photo_hash & 2) else classic_kb`, то есть палитра из двух
уместных режимов и хэш как разводящий. Правка распространяет уже принятое
решение с одной секции на все стадии рассказа, а не вводит новый принцип.

ПОРЯДОК СТАРШИНСТВА (структурные правила ВЫШЕ языка камеры):

    1. цифра на экране (`stat`)     -> static_hold   [не трогаем]
    2. под-кадр (`is_subcut`)       -> micro_drift   [не трогаем]
    3. начало раздела               -> slow_pull     [не трогаем]
    4. СТАДИЯ ДРАМАТУРГИИ           -> палитра       <- здесь работает модуль
    5. крупность кадра              -> сужение палитры
    6. хэш                          -> выбор внутри палитры

Первые три — это места, где смысл УЖЕ решает, и там менять нечего: цифра
обязана читаться, деталь не должна тянуть внимание, открывашка раздела —
это и есть establishing. Язык камеры занимает ровно ту пустоту, где
сегодня решает монетка.

ОТКУДА ВЗЯТА САМА ТАБЛИЦА. Не из головы и не из «кинематографично
звучит» — из функции стадии в документальном рассказе:

  заход-якорь     дать увидеть место целиком        -> отъезд, панорама
  постановка      контекст ещё расширяется          -> спокойный ход
  слом            зритель придвигается к правде     -> наезд, push
  доказательство  факт не спорит с движением        -> покой, микро-дрифт
  вывод           мысль отпускается                 -> отъезд, выдох
  перенос-на-зрителя  сближение с адресатом         -> наезд
  мостик          взгляд уводится дальше            -> панорама
  hook            удержание                         -> push  (уже так и есть)
  final           закрытие                          -> отъезд

ЧЕСТНЫЙ ПРЕДЕЛ. Измерить здесь можно две вещи: что движение перестало быть
случайным относительно смысла, и что новой монотонности не появилось —
обе меряются на самом плане, без рендера и без ключей. Чего измерить
НЕЛЬЗЯ: стало ли красивее. Это вердикт глазами владельца на готовом
ролике (Шаг 7.5), и выдавать одно за другое нельзя — ровно та подмена,
против которой в этом репозитории заведён золотой набор.
"""

#: Версия языка камеры. Входит в подпись рецепта рендера: другой выбор
#: движения — другой уже отрендеренный клип, и без подписи правка не
#: дошла бы до экрана на прогретом temp_smart/.
CAMERA_LANGUAGE_VERSION = 1

#: Палитра уместных режимов на каждую стадию рассказа. Порядок внутри
#: кортежа значения НЕ имеет — выбор делает хэш (см. `pick_from_palette`).
#: Пустой кортеж/отсутствие ключа = «у стадии нет мнения», прежнее
#: поведение.
#:
#: Имена стадий — ровно те, что проставляет `speech_planner.py`
#: (`arc_stage`), включая русские: второй копии словаря стадий здесь нет
#: специально, расхождение имён молча отключило бы весь слой.
STAGE_CAMERA = {
    # BLOCK-секции: семь стадий по позиции юнита внутри блока.
    "заход-якорь":        ("slow_pull", "horizontal_pan"),
    "постановка":         ("classic_kb", "horizontal_pan"),
    "слом":               ("snap_push", "classic_kb"),
    "доказательство":     ("static_hold", "micro_drift"),
    "вывод":              ("slow_pull", "classic_kb"),
    "перенос-на-зрителя": ("classic_kb", "snap_push"),
    "мостик":             ("horizontal_pan", "classic_kb"),
    # HOOK/FINAL: одна стадия на секцию.
    "hook":               ("snap_push", "classic_kb"),
    "final":              ("slow_pull", "static_hold"),
}

#: Направление зума, когда оно ОСМЫСЛЕННО на этой стадии. None = стадия
#: не имеет мнения, направление остаётся прежним (хэш + anti-repeat).
#:
#: Часть режимов задаёт направление сама и сильнее этой таблицы
#: (`snap_push` форсирует наезд, `slow_pull` — отъезд, см. kenburns()):
#: таблица нужна для режимов, которые направление НЕ задают —
#: `classic_kb`, `horizontal_pan`, `static_hold`, `micro_drift`.
STAGE_ZOOM_IN = {
    "заход-якорь":        False,   # открываем место
    "постановка":         False,   # контекст расширяется
    "слом":               True,    # придвигаемся к разоблачению
    "доказательство":     None,    # покой: направление не несёт смысла
    "вывод":              False,   # выдох
    "перенос-на-зрителя": True,    # сближение с адресатом
    "мостик":             None,    # уводим взгляд вбок, а не вглубь
    "hook":               True,
    "final":              False,
}

#: Крупность кадра сужает палитру ПОВЕРХ стадии — тот же принцип и та же
#: причина, что уже записаны в `choose_motion_mode()`: быстрый наезд на и
#: без того тесном кадре съедает сам объект, а панорама по крупному плану
#: превращается в мазню. Это не отмена стадии, а снятие с неё режимов,
#: которые физически спорят с кадром.
SHOT_SIZE_DROP = {
    "close":  ("snap_push", "horizontal_pan"),
    "detail": ("snap_push", "horizontal_pan"),
    "wide":   ("micro_drift",),
}


def camera_palette(arc_stage, shot_size=None):
    """Уместные режимы движения для стадии рассказа.

    Возвращает КОРТЕЖ режимов (может быть из одного) либо `()`, если
    стадии нет или она неизвестна — вызывающий код в этом случае обязан
    оставить прежнее поведение байт-в-байт.

    Сужение по крупности не имеет права опустошить палитру: если после
    снятия неуместных режимов не осталось ничего, возвращается палитра
    стадии как есть. Пустой ответ здесь означал бы «стадии нет», то есть
    молча отключил бы слой на самых тесных кадрах — а это как раз те
    кадры, где выбор движения важнее всего.
    """
    palette = STAGE_CAMERA.get(arc_stage) or ()
    if not palette:
        return ()
    drop = SHOT_SIZE_DROP.get(shot_size) or ()
    if drop:
        narrowed = tuple(m for m in palette if m not in drop)
        if narrowed:
            return narrowed
    return palette


def pick_from_palette(palette, photo_hash):
    """Выбор ВНУТРИ уместной палитры — тем же хэшем, что и раньше.

    Хэш здесь не принимает содержательного решения: он разводит между
    вариантами, которые стадия уже признала уместными. Ровно та роль,
    которая у него в правиле хука (`snap_push if (photo_hash & 2) else
    classic_kb`) была с самого начала.
    """
    if not palette:
        return None
    return palette[(int(photo_hash) >> 5) % len(palette)]


def stage_zoom_in(arc_stage):
    """Направление зума, если оно осмысленно на этой стадии, иначе None."""
    return STAGE_ZOOM_IN.get(arc_stage)


def describe(arc_stage, shot_size=None):
    """Человекочитаемое решение — для отчёта эпизода, не для рендера."""
    palette = camera_palette(arc_stage, shot_size)
    if not palette:
        return None
    return {"arc_stage": arc_stage, "palette": list(palette),
            "zoom_in": stage_zoom_in(arc_stage), "shot_size": shot_size}
