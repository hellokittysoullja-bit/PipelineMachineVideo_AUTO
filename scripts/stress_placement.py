"""Коррекция ударений для известных русских омографов — надстройка над
ruaccent (см. CLAUDE.md, раздел "Стресс-плейсмент по-русски").

КОНТЕКСТ. Прошлый заход (см. CLAUDE.md) протестировал ruaccent
(омограф-модель 'turbo', use_dictionary=True) и нашёл реальную,
воспроизводимую ошибку: "Мука для хлеба стоила..." — модель дала
"М+ука" (му́ка, страдание) вместо верного "мук+а" (мука́, продукт).
Вывод тогда был честным: ~90%+ точность, но не идеально — и решение
НЕ вшивать это в монтажные резы (резы в pipeline_smart.py завязаны на
границы тега [pause], то есть на паузы МЕЖДУ блоками, а не на конкретный
слог внутри слова — сам механизм физически не режет "по слогу", это
осталось верно и сейчас, см. CLAUDE.md).

ЭТОТ ЗАХОД (по прямому требованию пользователя "только улучшения, без
компромиссов") — не пытается заново решить задачу "резать по ударению"
(архитектурный вопрос без изменений), а исправляет саму ПРИЧИНУ, из-за
которой пункт был отложен: находит и чинит конкретные, измеренные ошибки
ruaccent на реальных примерах, калибруясь на живых прогонах (тот же
принцип, что уже применялся для RISKY_QUERY_MARGIN/PARTICLE_SCORE и т.д.
— не гадание, а измерение до вшивания).

МЕТОД (проверен вживую, не гипотеза). Для каждого известного омографа
(мука/замок — единственные два слова, где метод ДАЛ СТАБИЛЬНО ВЕРНЫЙ
результат на всех проверенных словоформах и контекстах; "атлас" тоже
исследован — там ruaccent путается даже при сильных подсказках
(например, "Картограф составил подробный атлас" всё равно даёт атла́с
вместо а́тлас), поэтому "атлас" СОЗНАТЕЛЬНО НЕ включён — честнее
поправить два слова надёжно, чем три ненадёжно):

1. По ключевым словам в окне вокруг омографа в РЕАЛЬНОМ тексте
   определяем, какой смысл имелся в виду (например, рядом с "мука"
   есть "хлеб"/"пшеничной"/"мельница" → смысл "мука́-продукт").
2. Строим короткий "зонд" — три слова через запятую: два опорных
   ключевых слова того же смысла + САМА словоформа как она встретилась
   в тексте (без изменений — не нужна лемматизация/морфология).
   Проверено вживую на 6+ словоформах каждого слова (им./род./тв. ед.,
   мн.ч.) — короткий зонд ("Пшеница, мельница, мука.") даёт ruaccent
   верное ударение НАДЁЖНЕЕ, чем сама исходная фраза (модели не мешает
   остальной контекст предложения).
3. Ударение из зонда переносится на то же слово в реальном тексте.

Если сигнала (ключевых слов) нет — слово НЕ трогается, остаётся ровно
то, что дал бы обычный ruaccent (без этого модуля). Это гарантирует
"только улучшение, никогда не хуже": вмешательство происходит ТОЛЬКО
там, где есть позитивное доказательство, никогда — на угадывании.

НЕ используется в монтажных резах или TTS-тегах сегодня — самостоятельный,
проверяемый инструмент. Безопасное применение уже сегодня — обогащение
`media_plan/speech_plan_annotated.txt` (Шаг 3.5, человек всё равно
перечитывает файл перед TTS согласно протоколу) точным ударением на
известных омографах, без риска для тайминга/аудио/рендера.
"""
import re

# "+" ВКЛЮЧЁН в класс "буквенных" символов — ruaccent вставляет "+" ПЕРЕД
# ударной буквой внутри слова ("М+ука"), без этого символ разрывал бы
# накопленное слово на 3 токена ("М", "+", "ука") и ломал бы позиционное
# сопоставление raw_tokens/base_tokens в accentize_with_homograph_correction()
# (реальный найденный баг — без него правки на "мука"/"замок" молча не
# срабатывали вообще, длины списков расходились и функция тихо возвращала
# необработанный baseline).
WORD_RE = re.compile(r"[А-Яа-яЁё+]+|[^А-Яа-яЁё+]+")

# Проверенные вживую (см. докстринг) словоформы ед./мн.ч. для каждого
# омографа — НЕ полная морфология, только формы, реально встречающиеся в
# повествовательном тексте канала. Ключ — форма в нижнем регистре.
HOMOGRAPH_FORMS = {
    "мука": "мука", "муки": "мука", "муке": "мука", "муку": "мука",
    "мукой": "мука", "мукою": "мука",
    "замок": "замок", "замка": "замок", "замку": "замок",
    "замком": "замок", "замке": "замок",
    "замки": "замок", "замков": "замок", "замками": "замок", "замках": "замок",
}

# (лемма, смысл) -> ключевые слова-триггеры (подстрокой, без регистра) +
# два опорных слова для зонда (сами проверены — дают стабильно верный
# результат в зонде, см. докстринг).
HOMOGRAPH_SENSES = {
    "мука": {
        "flour": {
            "triggers": ["хлеб", "пшениц", "ржан", "тест", "мельниц",
                         "амбар", "мешок", "пекар", "зерно", "выпечк",
                         "пирог", "блин", "овсян", "кукурузн", "просе"],
            "probe_anchors": ("Пшеница", "мельница"),
        },
        "suffering": {
            "triggers": ["голод", "боль", "страдан", "мучен", "пытк",
                         "совест", "душевн", "адск", "терп", "пекл",
                         "истязан"],
            "probe_anchors": ("Голод", "страдание"),
        },
    },
    "замок": {
        "castle": {
            "triggers": ["крепост", "рыцар", "корол", "башн", "стен",
                         "осад", "штурм", "граф", "герцог", "владени",
                         "феодал", "цитадел", "донжон", "гарнизон"],
            "probe_anchors": ("Крепость", "ров"),
        },
        "lock": {
            "triggers": ["дверь", "двер", "ключ", "взлом", "запер",
                         "навесн", "калитк", "засов", "отпер", "сундук"],
            "probe_anchors": ("Дверь", "ключ"),
        },
    },
}

CONTEXT_WINDOW_WORDS = 8

_accentizer = None


def _get_accentizer():
    global _accentizer
    if _accentizer is None:
        from ruaccent import RUAccent
        _accentizer = RUAccent()
        _accentizer.load(omograph_model_size="turbo", use_dictionary=True)
    return _accentizer


def _detect_sense(lemma, context_words_lower):
    senses = HOMOGRAPH_SENSES[lemma]
    for sense_name, cfg in senses.items():
        for trig in cfg["triggers"]:
            for w in context_words_lower:
                if trig in w:
                    return sense_name
    return None


def _probe_accent_for_form(form, lemma, sense):
    """Зонд: 'Опора1, опора2, форма.' -> берём ударение ruaccent для
    последнего слова зонда и переносим на реальную словоформу. Проверено
    вживую на всех формах в HOMOGRAPH_FORMS (см. докстринг модуля)."""
    a1, a2 = HOMOGRAPH_SENSES[lemma][sense]["probe_anchors"]
    probe = f"{a1}, {a2}, {form}."
    result = _get_accentizer().process_all(probe)
    tokens = WORD_RE.findall(result)
    word_tokens = [t for t in tokens if re.match(r"^[А-Яа-яЁё+]+$", t) and
                   re.sub(r"\+", "", t)]
    if not word_tokens:
        return None
    return word_tokens[-1]


def _match_case(accented_form, original_form):
    """Сохраняем регистр исходного слова (например, в начале предложения)."""
    if original_form[:1].isupper():
        stripped = accented_form.lstrip("+")
        if accented_form.startswith("+"):
            return "+" + stripped[:1].upper() + stripped[1:]
        return stripped[:1].upper() + stripped[1:]
    return accented_form


def accentize_with_homograph_correction(text):
    """Тот же результат, что accentizer.process_all(text), но с
    исправлением известных омографов (мука/замок) там, где в тексте есть
    контекстный сигнал смысла. Без сигнала — байт-в-байт как обычный
    ruaccent (см. докстринг модуля — гарантия "только улучшение")."""
    baseline = _get_accentizer().process_all(text)

    raw_tokens = WORD_RE.findall(text)
    base_tokens = WORD_RE.findall(baseline)
    if len(raw_tokens) != len(base_tokens):
        # Структурное расхождение (не должно происходить в норме) — не
        # рискуем спутать позиции, возвращаем необработанный baseline.
        return baseline

    raw_word_positions = [i for i, t in enumerate(raw_tokens)
                           if re.match(r"^[А-Яа-яЁё]+$", t)]
    lower_words = [raw_tokens[i].lower() for i in raw_word_positions]

    out_tokens = list(base_tokens)
    for pos_idx, tok_idx in enumerate(raw_word_positions):
        form_lower = lower_words[pos_idx]
        lemma = HOMOGRAPH_FORMS.get(form_lower)
        if lemma is None:
            continue
        lo = max(0, pos_idx - CONTEXT_WINDOW_WORDS)
        hi = min(len(lower_words), pos_idx + CONTEXT_WINDOW_WORDS + 1)
        context = lower_words[lo:pos_idx] + lower_words[pos_idx + 1:hi]
        sense = _detect_sense(lemma, context)
        if sense is None:
            continue   # нет сигнала — не трогаем, как и раньше
        # Зонд ВСЕГДА строится на СТРОЧНОЙ форме слова — реальный найденный
        # эффект: заглавная буква внутри зонда ("Пшеница, мельница, Мука.")
        # заставляет модель заподозрить имя собственное и перевернуть
        # предсказание ударения (проверено вживую: "Мука." в зонде даёт
        # М+ука, "мука." в том же зонде — верно мук+а). Регистр исходного
        # слова восстанавливается отдельно, через _match_case() ниже.
        corrected = _probe_accent_for_form(form_lower, lemma, sense)
        if corrected is None:
            continue
        out_tokens[tok_idx] = _match_case(corrected, raw_tokens[tok_idx])

    return "".join(out_tokens)
