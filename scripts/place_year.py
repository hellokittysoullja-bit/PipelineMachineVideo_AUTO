"""Место и год во фразе диктора — для подписи печатной машинкой.

Правило одно: подпись ставится ТОЛЬКО там, где во фразе ЯВНО названы и
место, и год. Ничего не додумывается: нет уверенности — подписи нет.
Детерминированно, локально, без моделей и сети.

Год — цифрами (1356) или словами в форме конкретного года («в тысяча триста
пятьдесят шестом году», «тысяча четыреста пятнадцатого года»). Десятилетия
и века («в тысяча сто семидесятых годах») — не год, подписи нет.

Место — имя собственное в той же фразе сразу после предлога места
(«при Пуатье», «под Азенкуром», «у Креси», «в Англии»). Падеж снимается
только там, где форма однозначна: несклоняемое слово (на гласную, кроме
«а/я») и форма предлога «при/в/во/на» с окончанием «-е» у слова на
согласную + «е» («при Азенкуре» -> «Азенкур») — неоднозначное отбрасывается.
"""
import re

_UNITS_ORD = {
    "перв": 1, "втор": 2, "трет": 3, "четвёрт": 4, "четверт": 4, "пят": 5, "шест": 6,
    "седьм": 7, "восьм": 8, "девят": 9,
}
_TEENS_ORD = {
    "десят": 10, "одиннадцат": 11, "двенадцат": 12, "тринадцат": 13, "четырнадцат": 14,
    "пятнадцат": 15, "шестнадцат": 16, "семнадцат": 17, "восемнадцат": 18, "девятнадцат": 19,
    "двадцат": 20, "тридцат": 30, "сороков": 40, "пятидесят": 50, "шестидесят": 60,
    "семидесят": 70, "восьмидесят": 80, "девяност": 90,
    "сот": 100, "двухсот": 200, "трёхсот": 300, "трехсот": 300, "четырёхсот": 400,
    "четырехсот": 400, "пятисот": 500, "шестисот": 600, "семисот": 700, "восьмисот": 800,
    "девятисот": 900, "тысячн": 1000,
}
_TENS_CARD = {"двадцать": 20, "тридцать": 30, "сорок": 40, "пятьдесят": 50, "шестьдесят": 60,
              "семьдесят": 70, "восемьдесят": 80, "девяносто": 90}
_HUND_CARD = {"сто": 100, "двести": 200, "триста": 300, "четыреста": 400, "пятьсот": 500,
              "шестьсот": 600, "семьсот": 700, "восемьсот": 800, "девятьсот": 900}
# Разговорная форма «тысяча трёхсот второго года» — сотни в родительном; тот же год.
_HUND_CARD.update({"ста": 100, "двухсот": 200, "трёхсот": 300, "трехсот": 300,
                   "четырёхсот": 400, "четырехсот": 400, "пятисот": 500, "шестисот": 600,
                   "семисот": 700, "восьмисот": 800, "девятисот": 900})
_TENS_CARD.update({"двадцати": 20, "тридцати": 30, "сорока": 40, "пятидесяти": 50,
                   "шестидесяти": 60, "семидесяти": 70, "восьмидесяти": 80, "девяноста": 90})
_ORD_ENDINGS = ("ом", "ого", "ый", "ой", "ий", "ем", "его", "ое", "ье", "ьего", "ьем", "ьему", "ому")

YEAR_MIN, YEAR_MAX = 500, 2100


def _ordinal_value(word):
    w = word.lower()
    for end in sorted(_ORD_ENDINGS, key=len, reverse=True):
        if w.endswith(end):
            stem = w[:-len(end)]
            break
    else:
        return None
    for table in (_TEENS_ORD, _UNITS_ORD):
        if stem in table:
            return table[stem]
    return None


_WORD = r"[А-Яа-яЁё]+"
# «в тысяча триста пятьдесят шестом году» / «тысяча четыреста пятнадцатого года»
_YEAR_WORDS_RE = re.compile(
    rf"\b(тысяча|две тысячи)((?:\s+{_WORD}){{1,3}}?)\s+(году|года|год)\b", re.I)
_YEAR_DIGITS_RE = re.compile(r"\b(1\d{3}|20\d{2}|[5-9]\d{2})\s*(?:-?м|-?го)?\s+(году|года|год|г\.)", re.I)


def years_in(text):
    """[(год, начало, конец)] — только КОНКРЕТНЫЕ годы."""
    out = []
    for m in _YEAR_WORDS_RE.finditer(text):
        base = 1000 if m.group(1).lower() == "тысяча" else 2000
        words = m.group(2).split()
        val, ok = base, True
        for k, wd in enumerate(words):
            lw = wd.lower()
            last = k == len(words) - 1
            if not last and lw in _HUND_CARD:
                val += _HUND_CARD[lw]
            elif not last and lw in _TENS_CARD:
                val += _TENS_CARD[lw]
            elif last and _ordinal_value(lw) is not None:
                val += _ordinal_value(lw) if _ordinal_value(lw) != 1000 else 0
            else:
                ok = False
                break
        if ok and words and YEAR_MIN <= val <= YEAR_MAX:
            out.append((val, m.start(), m.end()))
    for m in _YEAR_DIGITS_RE.finditer(text):
        val = int(m.group(1))
        if YEAR_MIN <= val <= YEAR_MAX:
            out.append((val, m.start(), m.end()))
    return sorted(out, key=lambda x: x[1])


_PLACE_PREP = r"(?:при|под|у|в|во|на|близ|возле|около)"
_CAP = r"[А-ЯЁ][а-яё]+(?:-[А-ЯЁ]?[а-яё]+)?"
# предлог места + имя собственное (предлог может стоять с заглавной в начале предложения)
_PLACE_RE = re.compile(rf"(?<![А-Яа-яЁё])((?i:{_PLACE_PREP}))\s+({_CAP})")
# «городом Линкольн», «у деревни Азенкур», «местечка Бремюль» — имя в приложении,
# в именительном падеже, берётся как есть
_APPOSITION_RE = re.compile(
    r"(?<![А-Яа-яЁё])(?:город|городом|городе|города|деревни|деревня|деревней|деревне|"
    rf"местечка|местечко|местечке|села|село|замка|замок|аббатства|крепости)\s+({_CAP})")
_VOWELS = "аеёиоуыэюя"
# Слова с заглавной, которые после предлога не место
_NOT_PLACE = {"январе", "феврале", "марте", "апреле", "мае", "июне", "июле", "августе",
              "сентябре", "октябре", "ноябре", "декабре", "бога", "боге", "господа", "христа",
              "средневековье"}   # «в Средневековье» — эпоха, не место (эп.04)


def _nominative(prep, word, confirm=None):
    """Именительный падеж места, если он восстанавливается однозначно; иначе None.

    confirm — множество слов сценария: форма на «-е» после согласной
    («при Таутоне») двусмысленна (Таутон? Таутона?), её принимает только
    подтверждение самим сценарием — где-то ещё в тексте стоит именно эта
    начальная форма."""
    lw = word.lower()
    p = prep.lower()
    if lw in _NOT_PLACE or len(lw) < 3:
        return None
    if p in ("в", "во", "на", "при", "о") and lw.endswith("ии"):
        return word[:-1] + "я"                     # во Франции -> Франция
    if lw[-1] in "оэ" or lw.endswith("ье") or (lw[-1] == "и" and lw[-2] not in "и"):
        return word                                # несклоняемое: Пуатье, Креси, Нанси
    # «-у/-ю» не берём: это чаще винительный («в Англию», «в Москву»), чем
    # несклоняемое имя — не уверены, подписи нет.
    if p == "под" and lw.endswith("ом") and lw[-3] not in _VOWELS:
        return word[:-2]                           # под Азенкуром -> Азенкур
    if p == "под" and lw.endswith("ой") and lw[-3] not in _VOWELS:
        return word[:-2] + "а"                     # под Москвой -> Москва
    if p in ("в", "во", "на", "при") and lw.endswith("е") and lw[-2] not in _VOWELS + "йь":
        for cand in (word[:-1], word[:-1] + "а"):
            if confirm and cand in confirm:
                return cand
        return None
    return None


# «Бамберг, небольшое княжество в Германии» — имя В ИМЕНИТЕЛЬНОМ, за ним
# запятая и пояснение «(прилагательное) княжество/город/деревня…». Живой
# промах эп.04: город в начале предложения не распознавался вовсе, страна
# после «в» распознавалась — и подпись уходила на страну. Между запятой и
# существительным — не больше двух прилагательных (по окончанию), иначе
# «Юниус, которого город выбирал» стал бы местом.
_APPOSITION_NOUNS = ("княжество", "город", "городок", "деревня", "деревушка", "село",
                     "селение", "местечко", "замок", "крепость", "аббатство", "монастырь",
                     "графство", "герцогство", "епископство", "столица", "порт", "остров")
_ADJ = r"[а-яё]+(?:ое|ый|ий|ой|ая|яя|ее|ие|ые)"
_APPOSITION_AFTER_RE = re.compile(
    rf"(?<![А-Яа-яЁё-])({_CAP}),\s+(?:(?!котор){_ADJ}\s+){{0,2}}"
    rf"(?:{'|'.join(_APPOSITION_NOUNS)})(?![а-яё])")

# Страны и крупные области — подпись «ГЕРМАНИЯ» там, где в той же фразе назван
# город, хуже подписи городом: место события — город. Список не исчерпывающий
# и не должен им быть: он нужен только для выбора между двумя найденными
# местами; область вне списка просто остаётся равноправным местом (и при двух
# равноправных местах подписи нет, как раньше).
REGIONS = {
    "европа", "германия", "франция", "англия", "испания", "италия", "швейцария", "австрия",
    "шотландия", "ирландия", "уэльс", "нидерланды", "голландия", "бельгия", "фландрия",
    "бургундия", "нормандия", "бретань", "аквитания", "гасконь", "прованс", "шампань",
    "португалия", "польша", "чехия", "богемия", "моравия", "венгрия", "швеция", "норвегия",
    "дания", "исландия", "финляндия", "россия", "литва", "пруссия", "саксония", "бавария",
    "швабия", "франкония", "вестфалия", "тироль", "кастилия", "арагон", "наварра",
    "каталония", "сицилия", "сардиния", "византия", "британия", "великобритания",
    "лотарингия", "эльзас", "савойя", "ломбардия", "тоскана",
}


_APPOSITION_OBLIQUE = ("городом", "городе", "города", "деревни", "деревней", "деревне",
                       "местечка", "местечке", "села", "замка", "аббатства", "крепости")


def _apposition_form(noun, word, confirm):
    """Имя в приложении обычно стоит в именительном («в городе Гларус»), но
    бывает и согласовано с падежом («в английском городе Ньюкасле» — эп.04).
    После косвенного падежа существительного форма с отрезанным окончанием
    берётся, ТОЛЬКО если сценарий сам подтверждает её где-то ещё
    («Ньюкасл, середина семнадцатого века»); иначе — как написано, как и
    раньше («городе Куртре» несклоняемое)."""
    if noun.lower() not in _APPOSITION_OBLIQUE or not confirm:
        return word
    lw = word.lower()
    cands = []
    if lw.endswith(("ом", "ем")):
        cands.append(word[:-2])
    if lw.endswith("ой"):
        cands.append(word[:-2] + "а")
    if lw[-1:] in ("е", "у", "а", "ю"):
        cands += [word[:-1], word[:-1] + "а"]
    for c in cands:
        if c in confirm:
            return c
    return word


def places_in(text, confirm=None):
    """[(место, начало, конец)] — имена собственные после предлога места, в
    приложении к «город/деревня/местечко…» и перед пояснением
    «X, (небольшое) княжество/город…»."""
    out = []
    for m in _PLACE_RE.finditer(text):
        nom = _nominative(m.group(1), m.group(2), confirm)
        if nom:
            out.append((nom, m.start(), m.end()))
    for m in _APPOSITION_RE.finditer(text):
        out.append((_apposition_form(m.group(0).split()[0], m.group(1), confirm), m.start(1), m.end()))
    for m in _APPOSITION_AFTER_RE.finditer(text):
        if m.group(1).lower() not in _NOT_PLACE:
            out.append((m.group(1), m.start(1), m.end()))
    return out


def is_region(place):
    """Страна или крупная область из REGIONS (не город)."""
    return str(place or "").lower() in REGIONS


_PERSON_TITLES = ("король", "короля", "королём", "королем", "королю", "королева", "герцог",
                  "герцога", "герцогом", "граф", "графа", "графом", "принц", "принца", "князь",
                  "князя", "князем", "император", "императора", "папа", "папы", "епископ",
                  "епископа", "монах", "монаха", "сэр", "сэра", "рыцарь", "рыцаря", "маршал",
                  "маршала", "барон", "барона", "лорд", "лорда", "святой", "святого")


_PERSON_VERBS = ("писал", "пишет", "написал", "сказал", "говорил", "говорит", "ответил",
                 "заявил", "приказал", "вспоминал", "умер", "родился", "правил", "правит")


def script_words(text):
    """Множество слов с заглавной во всём сценарии — подтверждение формы места.

    Слова, которые где-то в сценарии стоят после титула («король Генрих»,
    «герцог Карл») или перед другим именем с заглавной не в начале
    предложения («Генрих Благочестивый»), исключаются: «при Генрихе в 1241
    году» — время правления, а не место."""
    text = text or ""
    words = set(re.findall(_CAP, text))
    titles = "|".join(_PERSON_TITLES)
    persons = set(re.findall(rf"(?i:\b(?:{titles}))\s+({_CAP})", text))
    persons |= set(m.group(1) for m in re.finditer(rf"(?<=[а-яё,;:] )({_CAP})\s+[А-ЯЁ][а-яё]+", text))
    # «Шекспир пишет», «Яков сказал» — подлежащее при глаголе речи: человек.
    # Без этого «при Шекспире в 1600 году» подтверждалось бы как место
    # (эп.04: «в эпоху Шекспира», «Шекспир пишет «Макбета»»).
    verbs = "|".join(_PERSON_VERBS)
    persons |= set(re.findall(rf"({_CAP})\s+(?:[а-яё]+\s+)?(?:{verbs})\b", text))
    # и падежные формы того же человека: «Шекспира», «Шекспиру», «Шекспиром» —
    # иначе «при Шекспире» подтверждалось формой «Шекспира» как место.
    return {w for w in words - persons
            if not any(w[:-k] in persons for k in (1, 2) if len(w) - k >= 3)}


_MONTHS = {"января": 1, "февраля": 2, "марта": 3, "апреля": 4, "мая": 5, "июня": 6,
           "июля": 7, "августа": 8, "сентября": 9, "октября": 10, "ноября": 11, "декабря": 12}
_DAY_TENS = {"двадцать": 20, "тридцать": 30}
_DATE_RE = re.compile(
    rf"(?<![А-Яа-яЁё\d])((?:(?:двадцать|тридцать)\s+)?{_WORD}|\d{{1,2}})\s+"
    r"(января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря)\b", re.I)


def _day_value(token):
    t = token.lower().split()
    if len(t) == 1 and t[0].isdigit():
        v = int(t[0])
        return v if 1 <= v <= 31 else None
    base = 0
    if len(t) == 2:
        if t[0] not in _DAY_TENS:
            return None
        base = _DAY_TENS[t[0]]
    v = _ordinal_value(t[-1])
    if v is None or (base and v > 9):
        return None
    v += base
    return v if 1 <= v <= 31 else None


def dates_in(text):
    """[(подпись, начало, конец)] — даты фразы: «25 ОКТЯБРЯ 1415» (день, месяц
    и год рядом), «25 ОКТЯБРЯ» (без года), «1415» (только год). Число дня и
    год — словами или цифрами. Десятилетия и века — не дата (years_in)."""
    text = text or ""
    years = years_in(text)
    out, used = [], set()
    for m in _DATE_RE.finditer(text):
        day = _day_value(m.group(1))
        if day is None:
            # «пятое» без десятка не захватилось целиком — пробуем последнее слово
            last = m.group(1).split()[-1]
            day = _day_value(last)
            if day is None:
                continue
        label = f"{day} {m.group(2).upper()}"
        end = m.end()
        for k, (y, ya, yb) in enumerate(years):
            if 0 <= ya - m.end() <= 3:
                label += f" {y}"
                end = yb
                used.add(k)
                break
        out.append((label, m.start(), end))
    for k, (y, ya, yb) in enumerate(years):
        if k not in used:
            out.append((str(y), ya, yb))
    return sorted(out, key=lambda x: x[1])


# Имя места в НАЧАЛЕ предложения перед запятой и датой: «Азенкур, двадцать
# пятое октября…». Предлога нет, поэтому одно слово с заглавной в начале
# предложения само по себе ничего не доказывает («Теперь, …»). Берём его,
# только если (1) сразу после запятой идёт дата и (2) сценарий где-то ещё
# склоняет это имя («при Азенкуре», «Азенкура») — значит, это имя собственное.
_START_PLACE_RE = re.compile(rf"(?:^|(?<=[.!?…»]\s))({_CAP}),\s+")


def _declined_elsewhere(word, confirm):
    if not confirm or len(word) < 4:
        return False
    stem = word[:max(4, len(word) - 1)].lower()
    return any(c != word and c.lower().startswith(stem) for c in confirm)


def start_places_in(text, confirm=None):
    text = text or ""
    starts = [a for _l, a, _b in dates_in(text)]
    out = []
    for m in _START_PLACE_RE.finditer(text):
        word = m.group(1)
        if word.lower() in _NOT_PLACE or not _declined_elsewhere(word, confirm):
            continue
        if any(m.end() <= a <= m.end() + 1 for a in starts):
            out.append((word, m.start(1), m.end(1)))
    return out


def place_and_date(text, confirm=None):
    """(МЕСТО или None, ДАТА) — если во фразе ровно одна дата.

    Место — после предлога, в приложении («город X») или имя в начале предложения
    перед датой. Мест нет или неясно, какое (два равноправных) — подпись
    только с датой: число понятно и без места."""
    ds = {lab for lab, _a, _b in dates_in(text)}
    if len(ds) != 1:
        return None
    ps = {p.upper() for p, _a, _b in places_in(text or "", confirm) + start_places_in(text, confirm)}
    if len(ps) > 1:
        specific = {p for p in ps if not is_region(p)}
        if len(specific) == 1:
            ps = specific
    return (next(iter(ps)) if len(ps) == 1 else None), next(iter(ds))
