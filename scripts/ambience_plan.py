_TOKEN_RE = re.compile(r"[а-яa-z]+")


def score_text(text, vocab=None):
    """{атмосфера: балл} по тексту главы. Балл — сумма весов НАЙДЕННЫХ
    признаков, каждый признак считается один раз.

    Один раз, а не по числу вхождений: иначе одно часто повторяющееся слово
    («грязь» в эпизоде, который весь про грязь) перевешивало бы реальное
    описание места. Решает ШИРОТА совпадения, а не частота.

    Точные словоформы сравниваются по ЦЕЛОМУ слову, основы — по началу
    слова, и только длиной от AMBIENCE_MIN_STEM: голый поиск подстроки
    давал реальные промахи (см. комментарий у константы).
    """
    low = (text or "").lower().replace("ё", "е")
    tokens = set(_TOKEN_RE.findall(low))
    out = {}
    for name, groups in (vocab or AMBIENCE_VOCAB).items():
        total = 0
        for weight, kinds in groups.items():
            for word in kinds.get("word", ()):  # целое слово
                if word.replace("ё", "е") in tokens:
                    total += weight
            for stem in kinds.get("pref", ()):  # начало слова
                st = stem.replace("ё", "е")
                if any(t.startswith(st) for t in tokens):
                    total += weight
        if total:
            out[name] = total
    return out


def section_runs(blocks, sub_starts, total_dur):
    """[(имя_секции, начало, конец, [индексы блоков]), ...] — непрерывные
    участки одной секции сценария на аудио-шкале."""
    runs = []
    for i, b in enumerate(blocks or []):
        sec = str(b.get("section", ""))
        start = float(sub_starts[i]) if i < len(sub_starts) else 0.0
        if runs and runs[-1][0] == sec:
            runs[-1][3].append(i)
        else:
            runs.append([sec, start, None, [i]])
    for k, run in enumerate(runs):
        run[2] = runs[k + 1][1] if k + 1 < len(runs) else float(total_dur)
    return [tuple(r) for r in runs]


def _stable_seed(*parts):
    """Детерминированный seed из строк. hash() не годится: он солится от
    запуска к запуску, и одна и та же глава звучала бы разными участками
    при каждом рендере — то есть кэш клипов и звук разошлись бы молча."""
    h = 0
    for p in parts:
        for ch in str(p):
            h = (h * 131 + ord(ch)) & 0xFFFFFFFF
    return h


def plan_ambience(blocks, sub_starts, total_dur, block_text=None, vocab=None,
                  min_score=AMBIENCE_MIN_SCORE, min_run_sec=AMBIENCE_MIN_RUN_SEC,
                  max_distinct=AMBIENCE_MAX_DISTINCT,
                  switch_margin=AMBIENCE_SWITCH_MARGIN,
                  ambiguity_margin=AMBIENCE_AMBIGUITY_MARGIN,
                  llm_veto_fn=None):
    """[(начало, конец, атмосфера_или_None, seed, причина), ...] на весь ролик.

    Покрывает таймлайн БЕЗ дыр: участок без атмосферы — это явная запись
    с `None` и причиной, а не пропуск. Иначе «почему здесь тихо» опять
    существовало бы только в голове.

    llm_veto_fn(текст_главы) -> bool, опционально (AMBIENCE_LLM_VETO,
    scripts/ambience_director.build_veto_fn) — вызывается ТОЛЬКО когда
    словарь уже решил, что атмосфера нужна, и может её только СНЯТЬ
    (False), никогда не добавить то, что словарь сам не предложил. Эта
    односторонность и есть гарантия: вето физически не может ухудшить
    результат по сравнению со словарём без него, только убрать его
    собственные ложные срабатывания. Сбой вызова (модель упала, сеть) —
    fail-open, решение словаря остаётся как было.
    """
    block_text = block_text or (lambda b: str(b.get("text", "")))
    runs = section_runs(blocks, sub_starts, total_dur)

    # 1. Сырой выбор по тексту главы.
    raw = []
    for sec, start, end, idxs in runs:
        text = " ".join(block_text(blocks[i]) for i in idxs)
        scores = score_text(text, vocab)
        best, best_score, runner_up = None, 0, 0
        if scores:
            ranked = sorted(scores.items(), key=lambda kv: (-kv[1], kv[0]))
            best, best_score = ranked[0]
            runner_up = ranked[1][1] if len(ranked) > 1 else 0
        raw.append({"section": sec, "start": start, "end": end,
                    "bed": best, "score": best_score, "runner_up": runner_up,
                    "scores": scores, "text": text})

    # 2. Потолок на число разных атмосфер за эпизод. Оставляем самые
    #    уверенные; остальные главы теряют атмосферу, а не получают чужую.
    strength = {}
    for r in raw:
        if r["bed"] and r["score"] >= min_score:
            strength[r["bed"]] = strength.get(r["bed"], 0) + r["score"]
    allowed = {name for name, _ in sorted(strength.items(), key=lambda kv: (-kv[1], kv[0]))[:max_distinct]}

    # 3. Пороги, потолок и гистерезис смены — одним проходом.
    out, current = [], None
    for r in raw:
        bed, reason = None, None
        if not r["bed"] or r["score"] < min_score:
            reason = "low_confidence"
        elif r["score"] - r["runner_up"] < ambiguity_margin:
            # Две атмосферы вплотную — текст не говорит о месте определённо.
            reason = "ambiguous"
        elif r["bed"] not in allowed:
            reason = "over_distinct_cap"
        elif (r["end"] - r["start"]) < min_run_sec and r["bed"] != current:
            # Короткая глава не заводит СВОЮ атмосферу, но и не рвёт уже
            # идущую — если текущая разрешена, она просто продолжается.
            if current and current in allowed:
                bed, reason = current, "kept_short_run"
            else:
                reason = "run_too_short"
        elif current and r["bed"] != current:
            cur_score = r["scores"].get(current, 0)
            if r["score"] - cur_score < switch_margin:
                bed, reason = current, "switch_below_margin"
            else:
                bed, reason = r["bed"], "switched"
        else:
            bed, reason = r["bed"], "selected"
        # Решение СЛОВАРЯ запоминается ДО вето — это состояние гистерезиса
        # для следующих глав, и вето не имеет права его трогать.
        #
        # РЕАЛЬНЫЙ ДЕФЕКТ, воспроизведён 17.09, а не вычитан: `current = bed`
        # стояло ПОСЛЕ вето, то есть снятая у одной главы атмосфера обнуляла
        # продолжение у СЛЕДУЮЩЕЙ, которой модель не касалась вообще:
        #   без вето : HOOK windy selected · BLOCK1 windy selected · BLOCK2 windy selected
        #   вето на BLOCK1: HOOK windy · BLOCK1 None llm_veto · BLOCK2 None run_too_short
        # BLOCK2 терял фон по чужому вердикту, и причина в отчёте ВРАЛА
        # (`run_too_short` вместо честного «следствие вето соседа»). Это прямо
        # опровергало обещание односторонности, записанное абзацем выше.
        dict_bed = bed
        if bed and llm_veto_fn is not None:
            try:
                if not llm_veto_fn(r["text"]):
                    bed, reason = None, "llm_veto"
            except Exception:
                pass  # fail-open: сбой вызова оставляет решение словаря как было
        out.append({"section": r["section"], "start": r["start"], "end": r["end"],
                    "bed": bed, "reason": reason, "score": r["score"],
                    "runner_up": r["runner_up"],
                    "seed": _stable_seed(r["section"], bed or "silence")})
        current = dict_bed
    return out


def merge_adjacent(plan):
    """Соседние участки одной атмосферы склеиваются в один.

    Обязательно, а не косметика: на стыке двух участков стоят затухание и
    нарастание, и без склейки одна и та же атмосфера дважды за минуту
    «выключилась и включилась» — самый слышимый признак автомата.
    """
    out = []
    for seg in plan:
        if out and out[-1]["bed"] == seg["bed"]:
            out[-1] = dict(out[-1], end=seg["end"])
        else:
            out.append(dict(seg))
    return out


def summarize(plan):
    covered = sum(s["end"] - s["start"] for s in plan if s["bed"])
    total = (plan[-1]["end"] - plan[0]["start"]) if plan else 0.0
    by_bed, by_reason = {}, {}
    for s in plan:
        if s["bed"]:
            by_bed[s["bed"]] = round(by_bed.get(s["bed"], 0.0) + (s["end"] - s["start"]), 1)
        by_reason[s["reason"]] = by_reason.get(s["reason"], 0) + 1
    return {"segments": len(plan), "distinct_beds": len(by_bed),
            "covered_sec": round(covered, 1), "total_sec": round(total, 1),
            "covered_share": round(covered / total, 3) if total else 0.0,
            "seconds_by_bed": by_bed, "segments_by_reason": by_reason}
