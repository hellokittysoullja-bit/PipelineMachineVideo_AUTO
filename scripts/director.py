#!/usr/bin/env python3
"""Режиссёрские решения по СМЫСЛУ, а не по хэшу имени файла (ЧАСТЬ 6, 14, 17).

Раньше КАЖДОЕ творческое решение в кадре — зумить внутрь или наружу, куда
вести пан, насколько поднять контраст, какой поставить переход — бралось из
md5 пути к файлу или из номера стыка. Это давало разнообразие, но не смысл:
кадр под фразу-слом двигался ровно так же, как кадр под перечисление, пан с
одинаковой вероятностью уходил на объект и в пустое небо, а один и тот же
подъём контраста накладывался и на тёмный кадр, и на выбеленный.

Здесь те же решения принимаются от двух настоящих источников:
  * ТЕКСТ блока — какую работу он делает в сценарии (вопрос, слом, цифра,
    перечисление, тихий финал);
  * САМА КАРТИНКА — где в кадре визуальная масса, насколько кадр тёмный и
    плоский.

СВОЙСТВО, КОТОРОЕ ЗДЕСЬ ВАЖНЕЕ ТОЧНОСТИ: хуже случайного хэша быть не может.
Если классификатор не узнал реплику — он возвращает "neutral", и решение
отдаётся обратно хэшу, то есть ровно прежнему поведению. Ошибка
классификатора стоит одного кадра, поехавшего не в ту сторону — ровно то,
что раньше происходило на КАЖДОМ кадре по построению. Поэтому эвристики тут
намеренно консервативные: лучше промолчать ("neutral"), чем угадывать.

Модуль без состояния между вызовами и без тяжёлых зависимостей (PIL и numpy
и так обязательные) — им пользуются оба сборщика.
"""
import os
import re
import threading

try:
    import numpy as np
except ImportError:
    np = None   # без numpy анализ картинки выключается, решения падают обратно на хэш

from PIL import Image as PILImage


# ---------------------------------------------------------------- беаты
# "Беат" — не жанр и не эмоция, а РАБОТА, которую реплика делает в сценарии.
# Именно от неё зависит, как монтажёр ведёт кадр, а не от того, о чём текст.
BEAT_STAT = "stat"          # цифра на экране — её надо успеть прочитать
BEAT_QUESTION = "question"  # прямой вопрос зрителю — приём захвата
BEAT_REVEAL = "reveal"      # слом, контринтуитив — ради этого смотрят
BEAT_LIST = "list"          # перечисление — темп, а не вдумчивость
BEAT_ACTION = "action"      # энергия, восклицание
BEAT_QUIET = "quiet"        # спад, финал — отпускаем зрителя
BEAT_NEUTRAL = "neutral"    # не распознано -> решение отдаётся хэшу

# Маркеры общие для русской закадровой речи, НЕ привязаны к нише канала
# (ниша живёт в CHANNEL.md, это ядро — channel-agnostic, ЧАСТЬ 23).
REVEAL_MARKERS = (
    "на самом деле", "оказалось", "оказывается", "правда в том",
    "дело в том", "проблема в том", "секрет в том", "выяснилось",
    "вот только", "только вот", "в реальности", "вопреки", "однако",
    "но именно", "и вот тут", "а на деле",
)
# "Но"/"А" в НАЧАЛЕ реплики — тоже слом (ЧАСТЬ 8 прямо разрешает так начинать),
# но только в начале: внутри фразы это обычный союз и маркером быть не может.
REVEAL_OPENERS = ("но ", "а вот ", "и вот ", "только ")
LIST_MARKERS = (
    "во-первых", "во-вторых", "в-третьих", "первое", "второе", "третье",
    "и ещё", "ещё один", "ещё одна", "далее", "затем", "потом ещё",
)
QUIET_MARKERS = (
    "береги", "в конце концов", "вот и вс", "и всё", "на этом всё",
    "просто помни", "в итоге остаётся", "тем и заканчива",
)
# Цифра, которую зритель будет читать с экрана: процент, или число из 2+ цифр,
# или число с десятичной частью. Одиночная цифра ("два меча") — не статистика.
DIGIT_RE = re.compile(r'\d\s*%|\d+[.,]\d|\d{2,}')


def analyze_beat(text, section="", has_stat=False):
    """Какую работу делает эта реплика. Приоритет — от самого сильного
    экранного обязательства к самому слабому: плашку обязаны успеть прочитать,
    поэтому цифра перебивает всё остальное; дальше вопрос, слом, перечисление;
    финал по определению спад; и только потом — "не знаю"."""
    t = (text or "").strip()
    tl = t.lower()
    sec = (section or "").upper()
    if has_stat or DIGIT_RE.search(tl):
        return BEAT_STAT
    if "?" in t:
        return BEAT_QUESTION
    if any(m in tl for m in REVEAL_MARKERS) or tl.startswith(REVEAL_OPENERS):
        return BEAT_REVEAL
    if any(m in tl for m in LIST_MARKERS):
        return BEAT_LIST
    if sec.startswith("FINAL") or any(m in tl for m in QUIET_MARKERS):
        return BEAT_QUIET
    if "!" in t:
        return BEAT_ACTION
    return BEAT_NEUTRAL


# Наезд = "вот оно, смотри сюда". Отъезд = "выдохни, вот весь масштаб".
_ZOOM_IN_BEATS = frozenset((BEAT_STAT, BEAT_QUESTION, BEAT_REVEAL, BEAT_LIST, BEAT_ACTION))
_ZOOM_OUT_BEATS = frozenset((BEAT_QUIET,))


def zoom_intent(beat, is_section_start=False):
    """True = наезд, False = отъезд, None = мнения нет (решает хэш, как раньше).

    Открывашка раздела перебивает ТОЛЬКО нейтральный беат: общий план в начале
    главы — норма, но если первая же реплика раздела делает слом или несёт
    цифру, работа реплики важнее формальности открывашки."""
    if beat in _ZOOM_IN_BEATS:
        return True
    if beat in _ZOOM_OUT_BEATS:
        return False
    if is_section_start:
        return False    # нейтральное начало главы — отъезд, показываем, где мы
    return None


# Насколько дольше/короче держать кадр под этот беат. Множитель ложится
# ПОВЕРХ длительности по словам и до общей подгонки под аудио (fit_to_total),
# поэтому сумма всё равно сойдётся с озвучкой — меняются пропорции, не общая
# длина.
_BEAT_PACE = {
    BEAT_STAT: 1.12,      # цифру на плашке физически надо успеть прочитать
    BEAT_REVEAL: 1.15,    # слому нужно дать сесть, иначе он проскакивает
    BEAT_QUIET: 1.12,     # финал не режут часто
    BEAT_QUESTION: 1.05,
    BEAT_NEUTRAL: 1.0,
    BEAT_ACTION: 0.88,    # энергия = чаще режем
    BEAT_LIST: 0.85,      # перечисление на длинных кадрах умирает
}


def pace_multiplier(beat):
    return _BEAT_PACE.get(beat, 1.0)


# ------------------------------------------------------- анализ картинки
_comp_cache = {}
_comp_lock = threading.Lock()

# Ниже этого смещения визуальной массы считаем кадр отцентрованным: пан в
# любую сторону одинаково безопасен, и решение отдаётся хэшу — иначе на
# симметричных кадрах пан всегда шёл бы в одну и ту же сторону.
COMPOSITION_DEADZONE = 0.10

NEUTRAL_COMPOSITION = {"cx": 0.0, "cy": 0.0, "busyness": 0.5, "luma": 0.45, "spread": 0.22}


def frame_composition(path):
    """Где в кадре визуальная масса и какой кадр по свету.

    cx/cy — смещение центра массы перепадов яркости от центра кадра, доли
      [-1..1]; cx>0 — масса правее центра, cy>0 — ниже центра (как в индексах
      массива: строка 0 сверху).
    busyness — насколько кадр "тесный" (та же мера, что раньше считал
      estimate_busyness: уже крупный план не надо зумить ещё сильнее).
    luma/spread — средняя яркость и разброс яркости, 0..1. Это вход для
      shot matching: без них один и тот же подъём контраста ложился и на
      тёмный кадр, и на выбеленный.

    Считается на уменьшенной копии (96x54) — дёшево. Результат кэшируется:
    решения принимаются в последовательной фазе, но kenburns() может
    вызваться и из параллельной, поэтому кэш под замком."""
    if np is None:
        return dict(NEUTRAL_COMPOSITION)
    try:
        st = os.stat(path)
        key = (os.path.abspath(path), st.st_mtime_ns, st.st_size)
    except OSError:
        return dict(NEUTRAL_COMPOSITION)
    with _comp_lock:
        hit = _comp_cache.get(key)
    if hit is not None:
        return hit
    try:
        img = PILImage.open(path).convert("L").resize((96, 54))
        arr = np.asarray(img, dtype=np.float32)
    except Exception:
        return dict(NEUTRAL_COMPOSITION)

    gx = np.zeros_like(arr)
    gy = np.zeros_like(arr)
    gx[:, 1:] = np.abs(np.diff(arr, axis=1))
    gy[1:, :] = np.abs(np.diff(arr, axis=0))
    edge = gx + gy
    total = float(edge.sum())
    h, w = arr.shape
    if total < 1e-6:
        cx = cy = 0.0        # ровная заливка — никакой массы, центрировать нечего
    else:
        xs = (np.arange(w, dtype=np.float32) / (w - 1)) * 2.0 - 1.0
        ys = (np.arange(h, dtype=np.float32) / (h - 1)) * 2.0 - 1.0
        cx = float((edge.sum(axis=0) * xs).sum() / total)
        cy = float((edge.sum(axis=1) * ys).sum() / total)
    comp = {
        "cx": max(-1.0, min(1.0, cx)),
        "cy": max(-1.0, min(1.0, cy)),
        # та же формула, что была в estimate_busyness — поведение зума по
        # "тесноте" кадра не меняется, просто считается за один проход с остальным
        "busyness": float(min(1.0, (float(gx.mean()) + float(gy.mean())) / 40.0)),
        "luma": float(arr.mean() / 255.0),
        "spread": float(arr.std() / 255.0),
    }
    with _comp_lock:
        _comp_cache[key] = comp
    return comp


def pan_for_composition(comp, fallback_dir):
    """Вести кадр НА объект, а не наугад.

    Геометрия обоих путей (zoompan и параллакс) такая, что смещение растёт
    вместе с движением зума: при наезде кадр приходит к (dx,dy), при отъезде
    — стартует с (dx,dy) и расходится к центру. В обоих случаях "к объекту"
    это одно и то же направление, поэтому правило одно: если визуальная масса
    заметно смещена — идём к ней. Раньше направление выбирал хэш, и на кадре
    с объектом слева пан с вероятностью 1/2 уезжал вправо, выдавливая объект
    за рамку."""
    if not comp:
        return fallback_dir
    cx, cy = comp.get("cx", 0.0), comp.get("cy", 0.0)
    dx = 1 if cx > COMPOSITION_DEADZONE else (-1 if cx < -COMPOSITION_DEADZONE else 0)
    dy = 1 if cy > COMPOSITION_DEADZONE else (-1 if cy < -COMPOSITION_DEADZONE else 0)
    if dx == 0 and dy == 0:
        return fallback_dir   # кадр отцентрован — пусть направление даёт хэш
    return (dx, dy)


def grade_offsets(comp):
    """Shot matching: поправки к грейду ПОД КОНКРЕТНЫЙ КАДР.

    То, чем занимается колорист, когда сводит разнородный материал в один
    фильм. Раньше на все кадры накладывалась одна и та же кривая eq: выбеленный
    сток и тёмный кадр получали одинаковый подъём контраста, из-за чего первый
    оставался блёклым, а во втором тени сваливались в кашу.

    Возвращает дельты к contrast/brightness/saturation. Диапазоны узкие:
    задача — свести кадры друг к другу, а не перекрасить их."""
    if not comp:
        return {"dc": 0.0, "db": 0.0, "ds": 0.0}
    luma = comp.get("luma", 0.45)
    spread = comp.get("spread", 0.22)
    dc = db = ds = 0.0
    # Плоский кадр (мало разброса яркости) — «дымка», ему нужен контраст.
    # Уже контрастный — наоборот, добавка его только огрубит.
    if spread < 0.16:
        dc += 0.10
        ds += 0.04
    elif spread < 0.22:
        dc += 0.05
    elif spread > 0.30:
        dc -= 0.05
    # Тёмный кадр: приподнять и НЕ добивать контрастом, иначе тени в кашу.
    # Пересвеченный: чуть прибрать, света и так на пределе.
    if luma < 0.22:
        db += 0.035
        dc -= 0.03
    elif luma < 0.32:
        db += 0.015
    elif luma > 0.68:
        db -= 0.025
    elif luma > 0.58:
        db -= 0.010
    return {"dc": dc, "db": db, "ds": ds}


# ------------------------------------------------------------- переходы
# Пауза в сценарии — это РЕЖИССЁРСКАЯ РЕМАРКА, которую автор уже поставил
# руками. Она и так парсится (pause_after), но до сих пор влияла только на
# длительность кадра. Длинная пауза = смена мысли = зритель готов к заметному
# переходу; её отсутствие = мысль продолжается = только жёсткий рез.
LONG_PAUSE = 1.2     # две [pause] подряд и больше — автор явно просил большой вдох
NORMAL_PAUSE = 0.8   # одиночная [pause] — рядовая граница блока


def transition_kind(pause_after, h):
    """'visible' — заметный переход, 'hard' — жёсткий рез.

    На одиночной паузе заметный переход даётся редко (примерно каждый
    четвёртый) — в реальном монтаже дисcольв это исключение, а не норма.
    Отбор по хэшу стыка, чтобы одинаковые паузы не давали одинаковый ответ
    подряд."""
    if pause_after is None:
        return None                       # нет данных — вызывающий код решает по-старому
    if pause_after >= LONG_PAUSE:
        return "visible"
    if pause_after >= NORMAL_PAUSE:
        return "visible" if (h % 4 == 0) else "hard"
    return "hard"                         # [short pause] и меньше — мысль не прерывалась
