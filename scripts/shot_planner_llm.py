def unit_key(text):
    """Ключ ЮНИТА В ПЛАНЕ — по ТЕКСТУ фразы, и больше ни по чему.

    Номера сдвигаются от любой правки сценария выше по тексту, и план
    молча описывал бы чужую фразу. Ровно тот дефект, от которого уже
    защищается lock в шотлисте и ради которого `[shot:]` сделан инлайновым.

    ИЗ КЛЮЧА УБРАНЫ ВЕРСИЯ ПРОМПТА И ИМЯ МОДЕЛИ — правка по измеренному
    отказу, а не по вкусу. Планирование и рендер — РАЗНЫЕ запуски:
    план считают один раз, ролик собирают потом, и `LLAMA_MODEL_GGUF` при
    сборке обычно не выставлен (он для сборки не нужен). Тогда
    `os.path.basename("")` даёт пустую строку, ключ при рендере не
    совпадает с ключом при планировании, и `fill_briefs()` не находит НИ
    ОДНОГО юнита. Проверено прямым прогоном: план на диске, флаг включён,
    заявок 0 — молча.

    Это тот же класс «слой есть, и он ничего не даёт», который в этом
    репозитории уже пять раз находили глазами по готовому ролику
    (Openverse, Pixabay/Unsplash, reveal-акценты, фильтр по видео-пути,
    DEFLICKER под чужим именем) — здесь он был внутри самого режиссёра.

    Чем СПРАШИВАЛИ (промпт, модель) — свойство КЭША, а не плана: там
    пересчёт при смене модели и нужен. Ключ кэша — `cache_key()` ниже.
    """
    h = hashlib.md5()
    h.update(b"unit-v1\x00")
    h.update(" ".join((text or "").split()).encode("utf-8"))
    return h.hexdigest()[:16]








# Управляющие последовательности и одиночные символы, которыми llama-cli
# оформляет поток (цвет, спиннер загрузки, перерисовка строки). В JSON они
# попадают ВНУТРЬ слов — найдено на Q8-модели, где ответ выглядел так:
#     "subject?": "?? человек??",  "?": "shot?_?en?": "a??? person?"
# Q4 ту же ломку проскакивал случайно, то есть дефект был всё время и
# ждал другой модели или другой скорости вывода.
_CTRL_RE = re.compile(r"\x1b\[[0-9;?]*[ -/]*[@-~]|[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


def _clean_stream(text):
    """Снять оформление потока, не трогая сам текст."""
    return _CTRL_RE.sub("", text or "")


# --- ПРОВЕРКА ПОВЕРХ ОТВЕТА МОДЕЛИ -----------------------------------------
#
# Главная мысль, взятая из внешней оценки 16.09 и признанная верной:
# модель НЕ обязана быть права всегда — она обязана быть ПРАВА ИЛИ
# МОЛЧАТЬ. Тогда ухудшение становится структурно невозможным: заявка
# либо проходит проверку и улучшает слот, либо отбрасывается, и слот
# идёт ровно как сегодня.
#
# Это же чинит и то, на чём правка буксовала. Планка репозитория «ничьи
# и победы, ноль регрессов» на восьми вручную выбранных фразах
# превращалась в «никогда ничего не включать»: почти любое изменение
# где-то даст минус. С проверкой планка выполнима честно — минуса
# не бывает по построению, а не по результату замера.
#
# Проверки ДЕТЕРМИНИРОВАННЫЕ: ни ИИ, ни сети, ни порогов на глаз.

# «Человек вообще» приведёт современного человека в футболке. Историческому
# ролику нужен носитель эпохи. Список — из реальных промахов замера v2
# («a person standing up», «a person wearing full-body protective gear»).
#
# `soldier`/`soldiers`/`troops` ПОСТРОЕНЫ, ИЗМЕРЕНЫ И НЕ ВНЕСЕНЫ (16.09).
# Повод был настоящий: первый бесфлаговый прогон локальной модели выдал
# `a muddy trench with soldiers walking slowly` и заявка прошла целиком —
# `soldier` не якорь эпохи и не «человек вообще», а «trench» тянет Первую
# мировую. Ложных отказов на 142 брифах эталона слово не давало (0 из 142),
# и по этому числу правка выглядела бесплатной.
#
# Но негативный контроль на ЭТАЛОНЕ — не то же самое, что замер на
# МЕТРИКЕ. Пересчёт по сохранённым ответам моделей (одна переменная за
# раз, «в проде попаданий» = бриф там, где он принят, иначе запрос секции):
#
#   граница слова           Qwen3-4B 74 -> 74   30B 83 -> 83   доп.отказов 0
#   +soldier/troops         Qwen3-4B 74 -> 72   30B 83 -> 83   доп.отказов 15
#
# То есть слово стоит ДВА попадания на той самой маленькой модели, которая
# теперь мозг по умолчанию: она держит «soldier» за обычное обозначение
# человека своего времени, и правило выбивает у неё 15 законных заявок
# ради одной анахроничной. Планка репозитория — «ничьи и победы, ноль
# регрессов», и она не переписывается под собственный результат.
#
# Остаточный предел записан честно: заявка с «trench» сегодня проходит.
# Настоящий рычаг здесь — ПРОМПТ (требовать назвать носителя эпохи), а не
# список слов в проверке; это отдельная правка с отдельным замером.
GENERIC_PEOPLE = ("person", "people", "man", "woman", "human", "guy",
                  "someone", "individual")

# Совпадение по ГРАНИЦЕ СЛОВА, а не по пробелам с обеих сторон. Прежняя
# форма `f" {g} " in f" {low} "` пропускала слово, к которому прилипла
# пунктуация: «two rows of soldiers: one marching» и «a man, standing» не
# совпадали ни с чем. Найдено живым прогоном, проверено на эталоне: ноль
# ложных отказов из 142.
GENERIC_PEOPLE_RE = re.compile(
    r"\b(" + "|".join(GENERIC_PEOPLE) + r")\b", re.IGNORECASE)

# Слова, которые в стоке означают СОВРЕМЕННОЕ снаряжение. «protective gear»
# — реальный промах замера: приводит защитный костюм, а не доспех.
#
# «equipment» УБРАНО 15.09 по замеру на брифах автора эпизода 02. Оно
# попало сюда по догадке, рядом с единственным измеренным случаем, и
# оказалось обычным английским словом: бриф «an English archer's simple
# clothing and equipment», написанный человеком и ушедший в эпизод, эта
# строка отклоняла. Ни одного измеренного промаха ЗА «equipment» при этом
# нет — «protective gear» закрывает настоящий случай сам.
MODERN_GEAR = ("protective gear", "safety", "helmet cam", "uniform",
               "outfit", "costume")

# Бриф, который объясняет СВОЙ ЗАМЫСЕЛ («камень, СИМВОЛИЗИРУЮЩИЙ душевный
# груз»), описывает не вещь, а намерение — сфотографировать намерение
# нельзя. Найдено живым прогоном Qwen3.6-35B-A3B на психологическом
# сценарии: «a heavy stone weight resting on a wooden desk, symbolizing
# mental burden» и «a tangled ball of red yarn being pulled apart». Это
# те самые штампы из фотобанка, которые зритель читает как заглушку.
#
# Проверено на ВСЕХ измеренных брифах — эталон, запрос секции и пять
# моделей, 766 штук: НИ ОДНОГО ложного срабатывания. Класс узкий
# намеренно: список штампов по предметам (песочные часы, клубок) сюда НЕ
# вносится — песочные часы в ролике про Средневековье законны, и запрет
# по предмету отклонял бы годные кадры.
SYMBOL_TALK_RE = re.compile(
    r"\b(symboliz\w*|symbolic|symbolising|metaphor\w*|representing\s+the\b"
    r"|as\s+a\s+metaphor|conceptual)\b", re.I)


def _looks_like_translation(shot_en, phrase):
    """Ответ пересказывает фразу вместо описания кадра.

    Признак, взятый из реальных промахов («You have not been injured»,
    «This object will be revisited», «He was at their feet»): описание
    кадра — это ИМЕННАЯ ГРУППА, а не предложение с личной формой глагола
    и местоимением. Проверяется грубо и намеренно: цель — отсечь явное,
    а не разобрать английскую грамматику.
    """
    low = " " + (shot_en or "").lower() + " "
    pronouns = (" you ", " he ", " she ", " they ", " we ", " i ", " this ", " it ")
    verbs = (" was ", " were ", " will ", " have ", " has ", " is ", " are ",
             " must ", " should ", " need ")
    return any(p in low for p in pronouns) and any(v in low for v in verbs)


def channel_blocklist():
    """Термины, которых канал не хочет видеть — ИЗ УЖЕ СУЩЕСТВУЮЩЕГО списка.

    Второго словаря не заводится: `content_alt_blocklist` живёт в
    channel_profile.json, уже отсеивает кандидатов по их тексту и уже
    настраивается под нишу. Здесь тот же список применяется РАНЬШЕ — к
    тому, что мы собираемся ПОПРОСИТЬ. Просить то, что потом сами
    отсеем, бессмысленно.

    Fail-open: профиль не читается — проверка просто не применяется.
    """
    try:
        import pipeline_smart
        return tuple(pipeline_smart.CONTENT_ALT_BLOCKLIST)
    except Exception:
        return ()


def domain_anchor_words():
    """Слова, по которым видно, что кадр принадлежит МИРУ ЭТОГО КАНАЛА.

    ЧИТАЮТСЯ У КАНАЛА (`channel_profile.json` -> `shot_domain`), а не
    зашиты здесь. До 15.09 это был литеральный средневековый список, и он
    молча применялся бы к любому клону репозитория: канал про психологию,
    игры или сторителлинг получал бы требование «knight/armour/castle» и
    отказ на кадре обычного человека в комнате — то есть ровно на том
    кадре, который такой нише и нужен.

    Канал ничего не объявил — правило «человек без привязки к миру»
    ВЫКЛЮЧЕНО целиком. Это не послабление: включённое правило с чужим
    словарём отклоняет годные кадры, а выключенное просто пропускает их
    дальше, к гейтам отбора, которые и так стоят.

    Археологические слова в списке этого канала — из ЗАМЕРА, а не на
    всякий случай: правило отклоняло три ЭТАЛОННЫХ брифа подряд («a human
    skull from an archaeological excavation» и соседние), то есть весь
    блок эпизода про братскую могилу при Таутоне.
    """
    # ВЫКЛЮЧАТЕЛЬ ДЕЙСТВУЕТ И ЗДЕСЬ. Найдено собственным предохранителем:
    # SHOT_BRIEF_WORLD=off снимал доменное правило из ЗАДАНИЯ, но не из
    # ПРОВЕРКИ — она по-прежнему читала словарь профиля и на
    # психологическом сценарии зарубила 7 годных заявок из 17 («hand
    # resting on desk», «empty chair beside desk»). Половинчатый
    # выключатель хуже отсутствующего: задание больше не диктует чужой
    # мир, а проверка всё ещё требует его слов.
    if os.environ.get("SHOT_BRIEF_WORLD", "") == "off":
        return ()
    try:
        import pipeline_smart
        words = pipeline_smart.CHANNEL_PROFILE.get("shot_domain", {}).get(
            "anchor_words")
        return tuple(w.lower() for w in words) if words else ()
    except Exception:
        return ()


def brief_is_safe(shot_en, phrase, blocklist=None, era_words=None):
    """Можно ли выпускать эту заявку в отбор. (ok, причина отказа).

    Отказ — НЕ ошибка: слот просто идёт прежним путём. Поэтому проверки
    строгие, а не снисходительные: пропустить сомнительную заявку дороже,
    чем не проставить её вовсе.
    """
    if not shot_en:
        return False, "пусто"
    low = shot_en.lower()
    if _looks_like_translation(shot_en, phrase):
        return False, "пересказ фразы, а не описание кадра"
    # ПРАВИЛА ПРО СРАВНЕНИЯ ЗДЕСЬ НЕТ, и это осознанно.
    #
    # Внешняя оценка предлагала: «если во фразе есть сравнение (как,
    # словно, будто) — запрещаем показывать предмет сравнения». Идея
    # верная, реализация здесь невозможна: фраза РУССКАЯ («как
    # холодильник»), а описание кадра АНГЛИЙСКОЕ («a refrigerator»), и
    # сопоставить их без перевода нельзя. Первая версия этой проверки
    # сравнивала «холод» с «a refrigerator in a field» и была МЁРТВЫМ
    # КОДОМ — сработать не могла ни разу; доказал собственный тест, а не
    # рассуждение.
    #
    # Заводить мини-словарь русско-английских соответствий — ровно тот
    # ненадёжный приём, который в этом файле уже отвергнут для «crane»
    # (журавль законен на миниатюре) и в stress_placement для «атлас».
    # Случай сравнения закрывает ПРОМПТ v3, где это сказано прямо, и
    # замер показал, что он работает: «весил как холодильник» дало
    # «A sword strikes a helmet», а не холодильник.
    if SYMBOL_TALK_RE.search(low):
        return False, "символ вместо вещи"
    for g in MODERN_GEAR:
        if g in low:
            return False, f"современное снаряжение ({g})"
    # Блоклист канала. Закрывает случай, который правило сравнения НЕ
    # берёт по построению: в «поднимали КРАНОМ» нет союза «как» — это
    # творительный падеж внутри образа, а не сравнение. Правило
    # «предмет после как/словно» такое не поймает никогда, и притворяться
    # обратным нельзя. Зато «crane» — ровно то, чего канал про
    # Средневековье не хочет видеть ни при каких обстоятельствах, и для
    # этого в проекте уже есть список.
    for term in (blocklist if blocklist is not None else channel_blocklist()):
        t = str(term).lower().strip()
        if t and t in low:
            return False, f"блоклист канала ({t})"
    anchors = domain_anchor_words() if era_words is None else tuple(era_words)
    # Канал не объявил свой мир — правило не применяется вовсе.
    if anchors:
        has_anchor = any(e in low for e in anchors)
        if not has_anchor and GENERIC_PEOPLE_RE.search(low):
            return False, "человек без привязки к миру канала"
    return True, None








def load_plan(video_dir):
    """Готовый план с диска, или пустой словарь.

    ВЕРСИЯ ПРОМПТА ПРОВЕРЯЕТСЯ ЗДЕСЬ, а не в ключе юнита. Раньше она
    входила в `unit_key()`, и смена версии означала, что план перестаёт
    находиться ЦЕЛИКОМ и молча — ноль проставленных брифов вместо
    предупреждения. Это не защита от устаревшего плана, это тихий отказ,
    неотличимый от «плана нет».

    Теперь план собранный другой версией промпта ИСПОЛЬЗУЕТСЯ (он
    настоящий артефакт, и выбрасывать его молча хуже), но прогон громко
    говорит, что режиссёра надо перезапустить. Пересчёт же обеспечивает
    ключ КЭША (`cache_key`), куда версия и модель входят.
    """
    try:
        with open(os.path.join(video_dir, "media_plan", PLAN_NAME),
                  encoding="utf-8") as f:
            data = json.load(f)
        units = data.get("units")
        if not isinstance(units, dict):
            return {}
        made_by = data.get("version")
        current = PACKET_VERSION_OF.get(data.get("planner"))
        if current is not None and made_by is not None and made_by != current:
            print(f"  ВНИМАНИЕ: {PLAN_NAME} собран версией {made_by}, "
                  f"сейчас {current} — брифы от прошлой формулировки. "
                  f"Перезапусти режиссёра, чтобы пересчитать.")
        return units
    except Exception:
        return {}


def fill_briefs(blocks, plan):
    """Проставить `shot_brief` там, где автор его НЕ написал.

    Бриф автора не перезаписывается никогда и ни при каких условиях: он
    проверен человеком, а заявка модели — нет. Возвращает число реально
    заполненных юнитов.
    """
    if not plan:
        return 0
    filled = 0
    for b in blocks:
        if (b.get("shot_brief") or "").strip():
            continue
        got = plan.get(unit_key(b.get("text") or ""))
        if not got:
            continue
        ok, why = brief_is_safe(got.get("shot_en"), b.get("text") or "")
        if not ok:
            REJECTED.append({"text": (b.get("text") or "")[:80],
                             "shot_en": got.get("shot_en"), "reason": why})
            continue
        b["shot_brief"] = got["shot_en"]
        # Тип кадра модели уходит в ту же маршрутизацию по источникам, что
        # и авторская пометка `[object]`/`[scene]` в строке запроса.
        if got.get("function"):
            b["shot_type_hint"] = got["function"]
        filled += 1
    return filled




