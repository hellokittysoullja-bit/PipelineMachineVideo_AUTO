"""Слияние выдач НЕСКОЛЬКИХ формулировок одного слота (Reciprocal Rank Fusion).

Зачем отдельный модуль, а не ещё одна ветка в каскаде
-----------------------------------------------------
Каскад `_openverse_query_cascade()` уже строит несколько формулировок одного
запроса — но использует их как ЛЕСТНИЦУ ОТКАЗА: берёт первую, которая вообще
что-то вернула, и на этом останавливается. То есть более широкая формулировка
работает ТОЛЬКО когда точная не нашла ничего, и не работает в самом частом
случае — когда точная нашла НЕ ТО.

Оба брака, оставшиеся после маршрутизации по типу кадра (A/B 14.09), ровно
такие: на «european longsword blade macro» поиск Мет по отделу 4 честно
вернул предметы отдела и первым поставил арбалетный ворот; на «medieval camp
tent knight» архив первым поставил бронзовую статуэтку. В обоих случаях
формулировка вернула НЕПУСТУЮ выдачу, каскад остановился на ней, и второй
формулировки не существовало вовсе.

Почему слияние именно по РАНГАМ, а не по скорам
-----------------------------------------------
Этот репозиторий уже дважды заплатил за попытку сравнивать сырые скоры
разных запросов между собой (CLAUDE.md, «сырой косинус CLIP несопоставим
между разными текстами, и абсолютный порог по нему бессмыслен» — оба захода
на пиксельный классификатор анахронизмов). У поисковых API та же беда в
худшей форме: Мет вообще не отдаёт скор, Openverse отдаёт свой, Pexels свой,
и ни один не сопоставим с другим ни между источниками, ни между запросами.

RRF не смотрит на скоры вообще — только на ПОЗИЦИЮ кандидата в своём списке.
Поэтому он применим там, где сравнение скоров заведомо неверно, и это его
единственная причина быть выбранным здесь (а не потому, что «так принято в
поиске»).

Что он реально меняет в пуле
----------------------------
Кандидат, который стоит высоко у НЕСКОЛЬКИХ формулировок одного слота,
поднимается выше кандидата, найденного только одной. Это и есть тот самый
сигнал согласия, которого не было: арбалетный ворот выходит только на
полную странную фразу, а настоящий меч выходит и на неё, и на «medieval
sword». Пул от этого не растёт — меняется только ПОРЯДОК, то есть какие
`BASE_MIN_POOL` кандидатов вообще дойдут до оценки.

Честные пределы
---------------
* Слияние не добавляет в пул ничего, чего не нашла ни одна формулировка:
  если предмета нет в корпусе, никакой порядок его не создаст.
* Более широкая формулировка стоит РЕАЛЬНОГО запроса к API (каскад её
  экономил, пока точная давала непустой ответ) — цена измеряется и
  ограничена `MAX_VARIANTS`, а не объявляется нулевой.
* Слияние помогает ТОЛЬКО там, где формулировки дают разные списки. Там,
  где широкие формулировки пусты (замер: «medieval camp tent knight» —
  первые две ступени каскада отдают ноль), слияние по построению не меняет
  ничего, и выдавать это за улучшение нельзя.
* `DECAY` выставлен ЗАМЕРОМ, а не предпочтением, — см. комментарий к нему.
"""

# Классическая константа RRF (Cormack et al., 2009): гасит разницу между
# первыми местами, из-за которой один список мог бы единолично решать исход.
# k=60 из статьи рассчитан на выдачи в сотни позиций; здесь список источника
# — десятки кандидатов, и при k=60 разница между 1-м и 20-м местом (1/61 vs
# 1/80) почти исчезает, то есть ранг перестаёт значить что-либо. k=10
# сохраняет порядок внутри списка и при этом не даёт первому месту
# единоличного веса (1/11 против 1/30 на 20-й позиции).
RRF_K = 10.0

# Вес формулировки. ЗАМЕРЕНО, а не выбрано по замыслу.
#
# Первая версия ставила 0.5 («точная формулировка автора важнее выведенной из
# неё общей»). Прямой замер на том самом слоте, ради которого модуль написан
# («european longsword blade macro», отдел Мет 4), эту гипотезу ОПРОВЕРГ:
# списки двух формулировок пересекаются ровно одним кандидатом из 38, то есть
# СОГЛАСИЯ, на котором построен RRF, в этих данных почти нет — а раз нет
# согласия, убывающий вес превращает слияние в «взять точную формулировку»,
# то есть в точности в прежний каскад. Слияние измерялось как НО-ОП: первые
# восемь кандидатов совпадали с прежними до одного.
#
# При равном весе (1.0) те же данные дают другое: выдача Мет (алебарды,
# глефы — настоящее оружие) встаёт на позиции 1, 4, 6, 8 пробной выборки,
# тогда как при каскаде её в пуле не было ВООБЩЕ — он останавливался на
# точной формулировке, которую Мет не понял, и пул состоял из декорированных
# инициалов Чикаго.
#
# Это ровно тот же дефект и ровно то же лекарство, что этот репозиторий уже
# измерил уровнем выше — «все музеи, потом архив, потом сток» против
# чередования источников (CLAUDE.md, A/B 13.09): список, идущий подряд,
# вытесняет остальные из пробной выборки, и решает не качество, а позиция.
#
# Точная формулировка при этом НЕ теряет первенства: при равных рангах
# побеждает порядок первого появления, то есть она (см.
# test_exact_variant_wins_ties), а кандидат, найденный ДВУМЯ
# формулировками, по-прежнему обходит найденного одной (1/11 + 1/12 > 1/11).
DECAY = 1.0

# Потолок числа формулировок — прямая цена в запросах к API. Каскад этого
# канала даёт 2-3 ступени, так что 3 не режет ничего существующего, но
# закрывает случай «словарь расширили, и слот тихо стал стоить 6 запросов».
MAX_VARIANTS = 3

# Маркер версии для _selection_stack_signature(): слияние меняет ПОРЯДОК
# кандидатов в пуле, то есть кто вообще дойдёт до оценки, — на прогретом
# temp_smart/ без версии правка не дошла бы до экрана.
QUERY_FUSION_VERSION = 1


def variant_weights(n, decay=DECAY):
    """Веса формулировок по порядку: 1.0, decay, decay**2, ..."""
    return [decay ** i for i in range(max(0, n))]


def fuse(ranked_lists, key_fn, k=RRF_K, decay=DECAY, weights=None):
    """Слить списки выдач разных формулировок в один по RRF.

    ranked_lists — списки кандидатов В ПОРЯДКЕ ВЫДАЧИ, первый список
    считается самой точной формулировкой. key_fn(candidate) -> ключ
    тождества (у нас это id кандидата: один и тот же предмет Мет приходит
    по двум формулировкам одним и тем же объектом).

    Возвращает один список без повторов, отсортированный по убыванию
    RRF-веса. Порядок при равенстве весов — порядок первого появления
    (детерминизм: одинаковый вход даёт одинаковый выход, иначе кэш
    кандидатов и подпись отбора теряли бы смысл).
    """
    if weights is None:
        weights = variant_weights(len(ranked_lists), decay)
    scores = {}
    first_seen = {}
    objects = {}
    order = 0
    for li, lst in enumerate(ranked_lists):
        w = weights[li] if li < len(weights) else 0.0
        for rank, cand in enumerate(lst):
            try:
                key = key_fn(cand)
            except Exception:
                continue
            if key is None:
                continue
            if key not in first_seen:
                first_seen[key] = order
                objects[key] = cand
                order += 1
            scores[key] = scores.get(key, 0.0) + w / (k + rank + 1)
    return [objects[key] for key in
            sorted(scores, key=lambda key: (-scores[key], first_seen[key]))]
